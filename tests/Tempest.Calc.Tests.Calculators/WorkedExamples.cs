{
    public const string WriteVariable = "TEMPEST_WRITE_WORKED_EXAMPLES";

    public static IReadOnlyList<WorkedExample> All { get; } =
    [
        .. Mechanical.MechanicalWorkedExamples.All,
        .. Mechanical.MechanicalPortWorkedExamples.All,
        .. Structural.StructuralWorkedExamples.All,
        .. Structural.StructuralPortWorkedExamples.All,
        .. BuildingServices.BuildingServicesWorkedExamples.All,
        .. BuildingServices.BuildingServicesPortWorkedExamples.All,
        .. Electrical.ElectricalWorkedExamples.All,
        .. FluidPower.FluidPowerWorkedExamples.All,
        .. Electrical.ElectricalPortWorkedExamples.All,
    ];

    public static TheoryData<string> Keys => [.. All.Select(e => e.TemplateId + "/" + e.Slug)];

    public static WorkedExample Get(string key) => All.Single(e => e.TemplateId + "/" + e.Slug == key);

    public static string RepositoryRoot { get; } = FindRoot();

    public static string Folder(WorkedExample e) => Path.Combine(RepositoryRoot, "docs", "worked-examples", DisciplineFolder(e.TemplateId), e.TemplateId, e.Slug);

    /// <summary>The folder of a template's discipline under docs/worked-examples (building-services, electrical, fluid-power, mechanical, structural).</summary>
    public static string DisciplineFolder(string templateId) => AllCalculators.Get(templateId).Template.Discipline switch
    {
        CalcDiscipline.BuildingServices => "building-services",
        CalcDiscipline.FluidPower => "fluid-power",
        var d => d.ToString().ToLowerInvariant(),
    };

    /// <summary>The first line of the generated part of docs/worked-examples/README.md.</summary>
    public const string IndexStart = "<!-- Generated by WorkedExamples.Index from each example's run: regenerate with TEMPEST_WRITE_WORKED_EXAMPLES=1 dotnet test tests/Tempest.Calc.Tests.Calculators; do not edit by hand. -->";

    /// <summary>The last line of the generated part of docs/worked-examples/README.md.</summary>
    public const string IndexEnd = "<!-- End of the generated index. -->";

    /// <summary>
    /// The verdict cell of the index: "PASS — name" or "FAIL — name" of the governing check, exactly as the sheet lists it first, or "no pass/fail checks";
    /// a calculator behind a feature flag says so.
    /// </summary>
    public static string IndexVerdict(CalcTemplate template, CalcRunResult result) =>
        (result.Governing is { } g ? $"{(g.Passed ? "PASS" : "FAIL")} — {g.Name}" : "no pass/fail checks")
        + (template.FeatureFlag is { Length: > 0 } flag ? $" (feature flag `{flag}`, off by default)" : string.Empty);

    /// <summary>
    /// Shot-fix C3: the generated part of docs/worked-examples/README.md, the FAIL count and the index table, from the real run of every example
    /// (the hand-kept table named another governing check than the form and sheet.txt for many examples).
    /// </summary>
    public static string Index(IEnumerable<(WorkedExample Example, CalcRunResult Result)> runs)
    {
        var rows = runs
            .Select(r => (Discipline: DisciplineFolder(r.Example.TemplateId), r.Example, r.Result, Template: AllCalculators.Get(r.Example.TemplateId).Template))
            .OrderBy(r => r.Discipline, StringComparer.Ordinal).ThenBy(r => r.Example.TemplateId, StringComparer.Ordinal).ThenBy(r => r.Example.Slug, StringComparer.Ordinal)
            .ToList();
        var failing = rows.Count(r => r.Result.Governing is { Passed: false });

        var sb = new StringBuilder();
        sb.Append(IndexStart).Append('\n');
        sb.Append(failing).Append(" examples end on a **FAIL** governing check on purpose: they show how an overloaded or undersized design reads on the sheet. ");
        sb.Append("The verification footers in the stored sheets carry fixed placeholder values (hash `0000…`, engine `engine`); a sheet rendered in the product carries the real hash, engine version and test-run time.\n\n");
        sb.Append("| Discipline | Template | Example | Governing check |\n|---|---|---|---|\n");

        foreach (var r in rows)
            sb.Append("| ").Append(r.Discipline).Append(" | `").Append(r.Example.TemplateId).Append("` | [").Append(r.Example.Slug).Append("](")
              .Append(r.Discipline).Append('/').Append(r.Example.TemplateId).Append('/').Append(r.Example.Slug).Append("/README.md) | ")
              .Append(IndexVerdict(r.Template, r.Result)).Append(" |\n");

        sb.Append('\n').Append(IndexEnd).Append('\n');
        return sb.ToString();
    }

    /// <summary>The README text with its generated part replaced by <paramref name="index"/>; throws when the markers are missing.</summary>
    public static string WithIndex(string readme, string index)
    {
        var start = readme.IndexOf(IndexStart, StringComparison.Ordinal);
        var end = readme.IndexOf(IndexEnd, StringComparison.Ordinal);

        if (start < 0 || end < start)
            throw new InvalidOperationException("docs/worked-examples/README.md has no generated-index markers.");

        var after = end + IndexEnd.Length;

        if (after < readme.Length && readme[after] == '\n')
            after++;

        return string.Concat(readme.AsSpan(0, start), index, readme.AsSpan(after));
    }

    public static string Readme(WorkedExample e, CalcRunResult result, KnownAnswerOutcome outcome)
    {
        var sb = new StringBuilder();
        sb.Append("# ").Append(e.Title).Append(" (`").Append(e.TemplateId).Append("`)\n\n");
        sb.Append("**Source.** ").Append(e.Source.Title).Append(e.Source.Edition is { Length: > 0 } ? $", {e.Source.Edition}" : string.Empty).Append(", ").Append(e.Source.Location).Append(" — ").Append(e.Status).Append(".\n\n");
        sb.Append(e.Notes).Append("\n\n");
        sb.Append("| Input | Value | Source |\n|---|---|---|\n");

        foreach (var v in e.Inputs.Values.OrderBy(v => v.Symbol, StringComparer.Ordinal))
            sb.Append("| `").Append(v.Symbol).Append("` | ").Append(v.ValueText).Append(v.Unit is { Length: > 0 } ? " " + v.Unit : string.Empty).Append(" | ").Append(v.Provenance?.ToString() ?? "manual").Append(" |\n");

        // Shot-fix C4: the last column said PASS/FAIL for "computed matches expected", which read as the engineering verdict (Z_s and Z_s_max "PASS"
        // on a circuit that fails). It says whether the value matches the expectation; the verdict is the governing-check line below.
        sb.Append("\n| Output | Expected | Computed | Matches expected |\n|---|---|---|---|\n");

        foreach (var c in outcome.Checks)
            sb.Append("| `").Append(c.Symbol).Append("` | ").Append(c.Expected.ToString("G6", CultureInfo.InvariantCulture)).Append(' ').Append(c.Unit).Append(" | ").Append(c.Actual.ToString("G6", CultureInfo.InvariantCulture)).Append(' ').Append(c.Unit).Append(" | ").Append(c.Passed ? "yes" : "no").Append(" |\n");

        sb.Append("\nGoverning check: ").Append(result.Governing is { } g ? $"{g.Name} — {(g.Passed ? "PASS" : "FAIL")}{(g.HasUtilisation ? $" (utilisation {g.UtilisationText})" : string.Empty)}" : "none").Append(". Files: `inputs.json` (loads into the worksheet), `sheet.txt` (rendered text), `sheet.pdf` (rendered by the Desktop).\n");
        return sb.ToString();
    }

    /// <summary>
    /// The inputs as the worksheet form holds them straight after Import inputs (CalcSheetView.ShowTemplate with a stated seed, then ReadForm): a stated
    /// input as stated; an optional number or text the example leaves out stays blank (a blank number is not read; a blank text reads as an empty text);
    /// a required number with a default, a choice and a yes/no take the template's default with no source; a table or vector not stated is not carried.
    /// </summary>
    public static CalcInputSet AsImported(CalcTemplate template, CalcInputSet stated)
    {
        var set = new CalcInputSet { MadeOn = stated.MadeOn };

        foreach (var spec in template.Inputs)
        {
            if (stated.Find(spec.Symbol) is { } given)
            {
                set.Set(given);
                continue;
            }

            switch (spec.Kind)
            {
                case CalcInputKind.Quantity or CalcInputKind.Number when !spec.IsOptional:
                    set.Set(new CalcInputValue(spec.Symbol, Number: spec.Default ?? double.NaN, Unit: spec.Kind == CalcInputKind.Quantity ? spec.DefaultUnit : null, Provenance: CalcProvenance.Manual));
                    break;
                case CalcInputKind.Text:
                    set.Set(new CalcInputValue(spec.Symbol, Text: string.Empty, Provenance: CalcProvenance.Manual));
                    break;
                case CalcInputKind.Choice:
                    set.Set(new CalcInputValue(spec.Symbol, Text: spec.DefaultChoice, Provenance: CalcProvenance.Manual));
                    break;
                case CalcInputKind.Boolean:
                    set.Set(new CalcInputValue(spec.Symbol, Flag: spec.Default is { } d && d != 0, Provenance: CalcProvenance.Manual));
                    break;
            }
        }

        return set;
    }

    private static string FindRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);

        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "VERSION")))
            dir = dir.Parent;

        return dir?.FullName ?? AppContext.BaseDirectory;
    }
}

public sealed class WorkedExampleTests
{
    /// <summary>
    /// C-2 verification F5: the README wrote the governing utilisation with a formatter of its own ("1.044", "0.000" for a yes/no check) while the sheet, the form and the banner print
    /// two decimals rounded by the verdict ("1.05") and no utilisation for a yes/no check. The README's line is the sheet's: the guided test reads it as what the form must show.
    /// </summary>
    [Theory]
    [MemberData(nameof(WorkedExamples.Keys), MemberType = typeof(WorkedExamples))]
    [Trait("Verification", "WorkedExample")]
    public void The_Readme_Governing_Line_Is_The_Line_The_Sheet_Prints(string key)
    {
        var example = WorkedExamples.Get(key);
        var calculator = AllCalculators.Get(example.TemplateId);
        var result = CalcRunner.Run(calculator, example.Inputs);
        var outcome = KnownAnswerRunner.RunCase(calculator, new CalcTestCase(example.Slug, example.Title, example.Source, [.. example.Inputs.Values], example.Expected, example.Status));
        var line = WorkedExamples.Readme(example, result, outcome).Split('\n').Single(l => l.StartsWith("Governing check:", StringComparison.Ordinal));

        if (result.Governing is not { } governing)
        {
            Assert.StartsWith("Governing check: none.", line, StringComparison.Ordinal);
            return;
        }

        var expected = $"Governing check: {governing.Name} — {(governing.Passed ? "PASS" : "FAIL")}" + (governing.HasUtilisation ? $" (utilisation {governing.UtilisationText})" : string.Empty) + ".";
        Assert.StartsWith(expected, line, StringComparison.Ordinal);
        Assert.Equal(governing.HasUtilisation, line.Contains("(utilisation", StringComparison.Ordinal));

        if (governing.HasUtilisation)
            Assert.Matches(@"\(utilisation (?:\d+\.\d\d|0\.\d*[1-9]\d*|—)\)", line);
    }

    private static readonly string IndexPath = Path.Combine(WorkedExamples.RepositoryRoot, "docs", "worked-examples", "README.md");

    /// <summary>
    /// Shot-fix C3: the index table of docs/worked-examples/README.md is generated from the run of every example. Without the write variable the stored
    /// part must be what the run gives; with it (and TEMPEST_WRITE_WORKED_EXAMPLES=1) the part is rewritten.
    /// </summary>
    [Fact]
    [Trait("Verification", "WorkedExample")]
    public void The_Examples_Index_Is_Generated_From_The_Runs()
    {
        var index = WorkedExamples.Index(WorkedExamples.All.Select(e => (e, CalcRunner.Run(AllCalculators.Get(e.TemplateId), e.Inputs))));
        var stored = File.ReadAllText(IndexPath).Replace("\r\n", "\n", StringComparison.Ordinal);
        var expected = WorkedExamples.WithIndex(stored, index);

        if (Environment.GetEnvironmentVariable(WorkedExamples.WriteVariable) == "1")
        {
            File.WriteAllText(IndexPath, expected);
            return;
        }

        Assert.Equal(expected, stored);
    }

    /// <summary>
    /// Shot-fix C3: every row of the index names the governing check and the verdict that the example's stored sheet.txt lists first under "6. Checks"
    /// (or "no pass/fail checks" where the sheet has none), and every example has exactly one row.
    /// </summary>
    [Fact]
    [Trait("Verification", "WorkedExample")]
    public void Every_Index_Row_Names_The_Governing_Check_And_Verdict_Of_Its_Stored_Sheet()
    {
        var readme = File.ReadAllText(IndexPath).Replace("\r\n", "\n", StringComparison.Ordinal);
        var row = new System.Text.RegularExpressions.Regex(@"^\| (?<disc>[a-z-]+) \| `(?<id>[^`]+)` \| \[(?<slug>[^\]]+)\]\((?<link>[^)]+)\) \| (?<verdict>.+) \|$", System.Text.RegularExpressions.RegexOptions.Multiline);
        var rows = row.Matches(readme).ToList();
        Assert.Equal(WorkedExamples.All.Count, rows.Count);
        Assert.Equal(WorkedExamples.All.Select(e => e.TemplateId + "/" + e.Slug).Order(StringComparer.Ordinal), rows.Select(m => m.Groups["id"].Value + "/" + m.Groups["slug"].Value).Order(StringComparer.Ordinal));

        foreach (var m in rows)
        {
            var key = m.Groups["id"].Value + "/" + m.Groups["slug"].Value;
            var folder = Path.Combine(WorkedExamples.RepositoryRoot, "docs", "worked-examples", m.Groups["link"].Value.Replace("/README.md", string.Empty, StringComparison.Ordinal));
            Assert.Equal(WorkedExamples.Folder(WorkedExamples.Get(key)), Path.GetFullPath(folder));
            var sheet = File.ReadAllText(Path.Combine(folder, "sheet.txt")).Replace("\r\n", "\n", StringComparison.Ordinal);
            var checks = System.Text.RegularExpressions.Regex.Match(sheet, @"^6\. Checks[^\n]*\n(?<first>[^\n]*)", System.Text.RegularExpressions.RegexOptions.Multiline);
            Assert.True(checks.Success, $"{key}: sheet.txt has no '6. Checks' section.");
            var first = checks.Groups["first"].Value.Trim();
            var verdict = System.Text.RegularExpressions.Regex.Replace(m.Groups["verdict"].Value, @" \(feature flag `[^`]+`, off by default\)$", string.Empty);

            if (first == "None.")
            {
                Assert.True(verdict == "no pass/fail checks", $"{key}: the sheet has no checks; the index says '{verdict}'.");
                continue;
            }

            // The sheet lists "PASS  Name: detail" (a name may hold a colon of its own), so the row's verdict and name must begin the line.
            var parts = verdict.Split(" — ", 2, StringSplitOptions.None);
            Assert.True(parts.Length == 2 && parts[0] is "PASS" or "FAIL", $"{key}: cannot read the index verdict '{verdict}'.");
            Assert.True(first.StartsWith($"{parts[0]}  {parts[1]}: ", StringComparison.Ordinal), $"{key}: the index says '{verdict}'; sheet.txt lists '{first}' first.");
        }
    }

    /// <summary>
    /// Shot-fix C4: the index said the workshop radial passed ("Loop impedance within maximum") while the form, sheet.txt and the PDF fail it. Recomputed by
    /// hand (python3): R per metre at 70 °C = 0.017241 × 1.125 × (1 + 0.00393 × 50) = 0.0232075 Ω·mm²/m; R1 = 0.0232075 × 40 / 4 = 0.232075 Ω;
    /// R2 = 0.0232075 × 40 / 2.5 = 0.371319 Ω; Z_s = 0.8 + 0.232075 + 0.371319 = 1.403394 Ω; Z_s,max = 0.95 × 230 / (10 × 16) = 1.365625 Ω;
    /// u = 1.027657; I_f = 0.95 × 230 / 1.403394 = 155.69 A, below the 160 A instantaneous trip. The calculator is right and the example fails, as its notes say.
    /// </summary>
    [Fact]
    public void The_Workshop_Radial_Example_Fails_On_The_Hand_Computed_Loop_Impedance()
    {
        var example = WorkedExamples.Get("elec.fault-protection/workshop-radial-c16");
        var result = CalcRunner.Run(AllCalculators.Get(example.TemplateId), example.Inputs);
        Assert.Equal(1.403394, result.OutputSi("Z_s"), 6);
        Assert.Equal(1.365625, result.OutputSi("Z_s_max"), 6);
        Assert.Equal(1.027657, result.OutputSi("u_Zs"), 6);
        Assert.False(result.Governing!.Passed);
        Assert.Equal("FAIL — Fault current against the disconnection current", WorkedExamples.IndexVerdict(AllCalculators.Get(example.TemplateId).Template, result));
    }

    [Fact]
    public void A_Yes_No_Governing_Check_Has_No_Utilisation_In_Its_Readme_And_A_Failing_Ratio_Check_Is_Rounded_Up()
    {
        var fit = WorkedExamples.Get("mech.iso286-fit/h7-g6-25mm");
        var fitCalculator = AllCalculators.Get(fit.TemplateId);
        var fitResult = CalcRunner.Run(fitCalculator, fit.Inputs);
        Assert.False(fitResult.Governing!.HasUtilisation);
        var fitLine = WorkedExamples.Readme(fit, fitResult, KnownAnswerRunner.RunCase(fitCalculator, new CalcTestCase(fit.Slug, fit.Title, fit.Source, [.. fit.Inputs.Values], fit.Expected, fit.Status))).Split('\n').Single(l => l.StartsWith("Governing check:", StringComparison.Ordinal));
        Assert.DoesNotContain("utilisation", fitLine.Split(" Files:")[0], StringComparison.Ordinal);

        // A failing check prints its utilisation rounded up, as the sheet does: 1.0435 is 1.05 (the README printed 1.044).
        var member = WorkedExamples.Get("struct.en1993-member/uc-column-axial-moment");
        var memberCalculator = AllCalculators.Get(member.TemplateId);
        var memberResult = CalcRunner.Run(memberCalculator, member.Inputs);
        Assert.False(memberResult.Governing!.Passed);
        var memberLine = WorkedExamples.Readme(member, memberResult, KnownAnswerRunner.RunCase(memberCalculator, new CalcTestCase(member.Slug, member.Title, member.Source, [.. member.Inputs.Values], member.Expected, member.Status))).Split('\n').Single(l => l.StartsWith("Governing check:", StringComparison.Ordinal));
        Assert.Contains($"(utilisation {memberResult.Governing.UtilisationText})", memberLine, StringComparison.Ordinal);
        Assert.Equal(Math.Ceiling(memberResult.Governing.Utilisation * 100) / 100, double.Parse(memberResult.Governing.UtilisationText, CultureInfo.InvariantCulture), 9);
    }

    /// <summary>
    /// Shot-fix C1: 28 of the 54 templates' examples could not be checked as imported. Inputs added to a template after its example was written arrived
    /// on the form with the template default and no source, and Record check refused them ("X: give a source ... before it can be checked"). Every input
    /// the template declares is stated by the example with its source, or is an optional input the example deliberately leaves blank; the form the
    /// import fills then passes the provenance gate Record check and Issue apply.
    /// </summary>
    [Theory]
    [MemberData(nameof(WorkedExamples.Keys), MemberType = typeof(WorkedExamples))]
    [Trait("Verification", "WorkedExample")]
    public void Worked_Example_States_Every_Input_With_A_Source_So_It_Can_Be_Checked_As_Imported(string key)
    {
        var example = WorkedExamples.Get(key);
        var template = AllCalculators.Get(example.TemplateId).Template;

        var unstated = template.Inputs
            .Where(spec => example.Inputs.Find(spec.Symbol) is null && !(spec.IsOptional && spec.Kind is CalcInputKind.Quantity or CalcInputKind.Number or CalcInputKind.Text or CalcInputKind.Table or CalcInputKind.Vector))
            .Select(spec => $"{spec.Symbol} ({spec.Kind}, default {spec.Default?.ToString("R", CultureInfo.InvariantCulture) ?? spec.DefaultChoice ?? "none"} {spec.DefaultUnit})")
            .ToList();
        Assert.True(unstated.Count == 0, $"{key}: not stated by the example, so the form fills them unsourced: {string.Join("; ", unstated)}");

        var gate = CalcInputValidator.ValidateProvenanceForIssue(template, WorkedExamples.AsImported(template, example.Inputs));
        Assert.True(gate.Count == 0, $"{key}: {string.Join("; ", gate.Select(n => n.Message))}");

        // The stored file is what the import reads: it states the same inputs with the same sources.
        var stored = Path.Combine(WorkedExamples.Folder(example), "inputs.json");

        if (File.Exists(stored) && Environment.GetEnvironmentVariable(WorkedExamples.WriteVariable) != "1")
        {
            var (reloaded, _) = CalcInputJson.Read(File.ReadAllText(stored));
            Assert.Empty(CalcInputValidator.ValidateProvenanceForIssue(template, WorkedExamples.AsImported(template, reloaded)));
        }
    }

    [Theory]
    [MemberData(nameof(WorkedExamples.Keys), MemberType = typeof(WorkedExamples))]
    [Trait("Verification", "WorkedExample")]
    public void Worked_Example_Runs_And_Matches_Its_Expectations(string key)
    {
        var example = WorkedExamples.Get(key);
        var calculator = AllCalculators.Get(example.TemplateId);
        var result = CalcRunner.Run(calculator, example.Inputs);
        Assert.False(result.IsBlocked, string.Join("; ", result.Blocks.Select(b => b.Message)));
        Assert.Empty(CalcInputValidator.ValidateProvenanceForIssue(calculator.Template, example.Inputs));

        var testCase = new CalcTestCase(example.Slug, example.Title, example.Source, [.. example.Inputs.Values], example.Expected, example.Status);
        var outcome = KnownAnswerRunner.RunCase(calculator, testCase);
        Assert.True(outcome.Passed, string.Join("; ", outcome.Checks.Where(c => !c.Passed).Select(c => $"{c.Symbol}: expected {c.Expected} {c.Unit}, got {c.Actual:G6} {c.Problem}")));

        var folder = WorkedExamples.Folder(example);
        var json = CalcInputJson.Write(example.Inputs);
        var sheet = CalcSheetTextRenderer.Render(CalcSheetBuilder.Build(calculator.Template, example.Inputs, result,
            new CalcSheetHeader("Worked example", example.Slug, calculator.Template.Title, "A", CalcSheetStatus.Draft, "TempestOS", null, null, null, null),
            GoldenFiles.FixedFooter(calculator.Template, KnownAnswerRunner.Run(calculator).Passed, calculator.Template.TestCases.Count)));

        if (Environment.GetEnvironmentVariable(WorkedExamples.WriteVariable) == "1")
        {
            Directory.CreateDirectory(folder);
            File.WriteAllText(Path.Combine(folder, "inputs.json"), json);
            File.WriteAllText(Path.Combine(folder, "README.md"), WorkedExamples.Readme(example, result, outcome));
            File.WriteAllText(Path.Combine(folder, "sheet.txt"), sheet);
            return;
        }

        var stored = Path.Combine(folder, "inputs.json");
        Assert.True(File.Exists(stored), $"{stored} is missing; run with {WorkedExamples.WriteVariable}=1 to write it.");
        var (reloaded, notices) = CalcInputJson.Read(File.ReadAllText(stored));
        Assert.Empty(notices);
        Assert.False(CalcRunner.Run(calculator, reloaded).IsBlocked);
        Assert.Equal(json.Replace("\r\n", "\n", StringComparison.Ordinal), File.ReadAllText(stored).Replace("\r\n", "\n", StringComparison.Ordinal));
    }
